/** "9:30 AM" / "9:30 a. m." from "09:30". */
export function formatHour(hhmm: string, lang: Lang): string {
  const [h, m] = hhmm.split(":").map(Number);
  const d = new Date(Date.UTC(2026, 0, 1, h, m));
  return new Intl.DateTimeFormat(lang === "es" ? "es-US" : "en-US", { hour: "numeric", minute: m ? "2-digit" : undefined, timeZone: "UTC" }).format(d);
}
